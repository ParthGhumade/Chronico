import json
import os
from typing import Any
from dotenv import load_dotenv
from google import genai
from google.genai import types

from backend.config import DEFAULT_MODEL_NAME
from backend.models import Context, VerificationResult

load_dotenv()

VERIFIER_SYSTEM_INSTRUCTION = """You are a factual verification assistant.

Your task is to compare the generated draft report against the original shared context (including raw narration, event details, school details, and photos).

Your job is NOT to improve writing style, flow, or grammar.
Your job is ONLY to verify factual correctness and detect hallucinations.

Check for:
- Hallucinations: any facts, guests, activities, speeches, or details added to the report that DO NOT exist or are not implied in the original context or raw narration.
- Missing key activities or people mentioned in the original narration.
- Wrong names, titles, dates, venues, or numbers.
- Contradictions between the draft report and the original context.

Output JSON with exact structure:
{
  "status": "approved" | "retry",
  "issues": ["Issue description 1", "Issue description 2"]
}

If the report strictly adheres to the facts in the context without adding false or extra ungrounded information, set status to "approved" and issues to an empty list [].
If any fake stuff, hallucinations, or contradictions are detected, set status to "retry" and provide specific actionable feedback in issues."""


def run_verifier_agent(
    context: Context | dict[str, Any],
    draft_report: str,
    api_key: str | None = None,
    model_name: str | None = None,
) -> VerificationResult:
    """
    Verifier Agent function that evaluates a draft report against original narration and context.

    Args:
        context: Shared Context (Context Pydantic model or dict).
        draft_report: Draft report text generated by Writer agent.
        api_key: Optional Gemini API key.
        model_name: Optional Gemini model name.

    Returns:
        VerificationResult object with status ('approved' or 'retry') and issues list.
    """
    resolved_api_key = api_key or os.getenv("GEMINI_API_KEY")
    if not resolved_api_key:
        raise ValueError(
            "Gemini API key is required. Please set GEMINI_API_KEY environment variable or pass api_key."
        )

    resolved_model = model_name or DEFAULT_MODEL_NAME

    if isinstance(context, Context):
        context_dict = context.model_dump()
    else:
        context_dict = context

    context_str = json.dumps(context_dict, ensure_ascii=False, indent=2)

    prompt = f"""Original Shared Context & Raw Narration:
{context_str}

Draft Report to Verify:
{draft_report}

Verify if the draft report contains any hallucinated facts, false information, missing details, or ungrounded additions. Return the verification JSON."""

    client = genai.Client(api_key=resolved_api_key)

    config = types.GenerateContentConfig(
        system_instruction=VERIFIER_SYSTEM_INSTRUCTION,
        temperature=0.1,  # Low temperature for deterministic verification logic
        response_mime_type="application/json",
        response_schema=VerificationResult,
    )

    try:
        response = client.models.generate_content(
            model=resolved_model,
            contents=prompt,
            config=config,
        )

        raw_text = response.text.strip() if response.text else "{}"
        data = json.loads(raw_text)
        return VerificationResult(**data)
    except Exception as e:
        # Fallback or re-raise if schema parsing fails
        try:
            clean_text = response.text.strip("```json").strip("```").strip() if response.text else "{}"
            data = json.loads(clean_text)
            return VerificationResult(**data)
        except Exception:
            raise RuntimeError(f"Verifier agent failed to return valid VerificationResult: {e}")
